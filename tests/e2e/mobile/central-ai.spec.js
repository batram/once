for (const width of [390, 1280]) for (const theme of ["light", "dark"]) test(`reader AI rewrites from the speech bar and undoes one step ${width} ${theme}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  const story = await seedFixtureStories(page)
  await openSettingsSection(page, "addons")
  await installAiAddon(page, new URL(page.url()).origin)
  await openSettingsSection(page, "theme")
  await page.locator("#theme_select").selectOption(theme)
  await page.getByTestId("stories-menu").click()
  await story.getByTestId("story-menu-button").click()
  await page.getByTestId("story-menu-open-reader").click()
  const frame = page.frameLocator('iframe[title="Reader mode"]')
  const article = frame.locator("article").first(), heading = frame.locator("main h1")
  const bar = page.getByTestId("reader-tts-bar")
  const before = await article.innerHTML(), title = await heading.textContent()
  await expect(frame.locator(".reader-ai")).toHaveCount(0)
  await expect(bar.getByRole("button", { name: "Undo", exact: true })).toBeHidden()
  await bar.getByRole("button", { name: "Rewrite with AI", exact: true }).click()
  await expect(heading).toHaveText("Fixture rewritten title")
  await expect(article.locator("li")).toHaveText(["First point", "Second point"])
  await expect(article.locator("li.tts-segment"), "read-aloud segments follow the rewritten article").toHaveCount(2)
  await expect(page.locator("#reader_ai_status")).toBeHidden()
  await expect(bar.getByRole("button", { name: "Rewrite with AI", exact: true })).toHaveAttribute("title", /fixture/)
  await page.screenshot({ path: `test-results/ai-reader-${width}-${theme}.png`, fullPage: true })
  // A second rewrite adds a step: the first Undo returns to the first rewrite, the second to the extraction.
  const answered = page.waitForResponse(response => response.url().includes("/ai-addon/") && response.request().method() === "POST")
  await bar.getByRole("button", { name: "Rewrite with AI", exact: true }).click()
  await answered
  // Undo is disabled while the request runs, so enabled means the second result is in place.
  await expect(bar.getByRole("button", { name: "Undo", exact: true })).toBeEnabled()
  await bar.getByRole("button", { name: "Undo", exact: true }).click()
  await expect(heading).toHaveText("Fixture rewritten title")
  await expect(bar.getByRole("button", { name: "Undo", exact: true })).toBeVisible()
  await bar.getByRole("button", { name: "Undo", exact: true }).click()
  await expect(heading).toHaveText(title)
  expect(await article.innerHTML()).toBe(before)
  await expect(bar.getByRole("button", { name: "Undo", exact: true })).toBeHidden()
})

test("shared sync uses one unlock while both dataset switches remain independent", async ({ page, request, baseURL }) => {
  const server = new URL(baseURL).origin
  const database = "central_ai_sync"
  await request.post(`${server}/test/databases/${database}/reset`, { data: { docs: [] } })
  await page.setViewportSize({ width: 390, height: 844 })
  await gotoMobileApp(page)
  await openSettingsSection(page, "ai")
  await configureCentralAi(page, new URL(page.url()).origin)
  await page.getByRole("button", { name: /^Sync:/ }).click()
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await page.getByTestId("sync-url").fill(`${server.replace("http://", "http://once-test:once-test@")}/db/${database}`)
  await page.getByTestId("save-sync").click()
  await expect(page.getByTestId("sync-status")).toHaveAttribute("data-state", "up-to-date", { timeout: 15000 })
  await page.locator('[data-sync-target="addons"]').click()
  await page.getByLabel("Sync passphrase (at least 12 characters)", { exact: true }).fill("fixture shared passphrase")
  await page.getByLabel("Confirm sync passphrase", { exact: true }).fill("fixture shared passphrase")
  await page.getByRole("button", { name: "Enable encrypted sync", exact: true }).click()
  await expect(page.getByTestId("addon-vault-recovery-key")).toBeVisible()
  await page.getByRole("button", { name: "I saved my recovery key", exact: true }).click()
  await page.getByTestId("sync-dataset-ai").check()
  await expect(page.getByTestId("sync-dataset-ai")).toBeChecked()
  await page.getByTestId("sync-dataset-addons").uncheck()
  await expect(page.getByTestId("sync-dataset-addons")).not.toBeChecked()
  await page.screenshot({ path: "test-results/ai-shared-sync.png", fullPage: true })
  await page.getByRole("button", { name: "Lock and forget", exact: true }).click()
  await page.getByLabel("Sync passphrase or recovery key", { exact: true }).fill("fixture shared passphrase")
  await page.getByRole("button", { name: "Unlock sync", exact: true }).click()
  await expect(page.getByTestId("sync-dataset-ai")).toBeChecked()
  await expect(page.getByTestId("sync-dataset-addons")).not.toBeChecked()
  await page.getByTestId("sync-dataset-ai").uncheck()
  await expect(page.getByTestId("sync-dataset-ai")).not.toBeChecked()
  await openSettingsSection(page, "ai")
  await expect(page.getByRole("button", { name: "Default model: Fixture AI · fixture", exact: true })).toBeVisible()
})

test("reader cancellation retains content and ignores a delayed provider result", async ({ page }) => {
  const story = await seedFixtureStories(page)
  await openSettingsSection(page, "addons")
  await installAiAddon(page, new URL(page.url()).origin)
  let release
  const held = new Promise(resolve => { release = resolve })
  await page.route("**/ai-addon/v1/chat/completions", async route => {
    await held
    await route.abort().catch(() => {})
  })
  await page.getByTestId("stories-menu").click()
  await story.getByTestId("story-menu-button").click()
  await page.getByTestId("story-menu-open-reader").click()
  const frame = page.frameLocator('iframe[title="Reader mode"]')
  const bar = page.getByTestId("reader-tts-bar"), status = page.locator("#reader_ai_status")
  const before = await frame.locator("article").first().innerHTML()
  await bar.getByRole("button", { name: "Rewrite with AI", exact: true }).click()
  await expect(status).toContainText("Waiting for the model")
  await bar.getByRole("button", { name: "Cancel AI rewrite", exact: true }).click()
  await expect(status).toBeHidden()
  release()
  expect(await frame.locator("article").first().innerHTML()).toBe(before)
  await expect(bar.getByRole("button", { name: "Undo", exact: true })).toBeHidden()
  await expect(bar.getByRole("button", { name: "Rewrite with AI", exact: true })).toBeVisible()
})
