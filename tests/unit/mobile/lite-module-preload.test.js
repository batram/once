test("side-effect bootstrap completes before bundled modules evaluate", async t => {
  const { bundleStaticModules } = require("../../../scripts/bundle-lite-extension-modules")
  const { registerHooks } = require("node:module")
  const { pathToFileURL } = require("node:url")
  const { root, write } = fixture(t)
  write("package.json", JSON.stringify({ type: "module" }))
  write("js/vapi-common.js", "globalThis.__onceBootstrap = 1;")
  write("js/vapi-background.js", "if (globalThis.__onceBootstrap !== 1) throw Error('common missing'); globalThis.__onceBootstrap = 2;")
  write("js/vapi-background-ext.js", "if (globalThis.__onceBootstrap !== 2) throw Error('background missing'); globalThis.__onceBootstrap = 3;")
  write("js/shared.js", "if (globalThis.__onceBootstrap !== 3) throw Error('bootstrap missing'); export const value = 7;")
  write("js/start.js", 'import "./vapi-common.js"; import "./vapi-background.js"; import "./vapi-background-ext.js"; import { value } from "./shared.js"; globalThis.__onceBootstrapResult = value;')
  const prefix = pathToFileURL(fs.realpathSync(root) + path.sep).href
  const hooks = registerHooks({ resolve(specifier, context, next) {
    if (specifier.startsWith("/js/") && context.parentURL?.startsWith(prefix)) return next(new URL("." + specifier, prefix).href, context)
    return next(specifier, context)
  } })
  t.after(() => { hooks.deregister(); Reflect.deleteProperty(globalThis, "__onceBootstrap"); Reflect.deleteProperty(globalThis, "__onceBootstrapResult") })
  await bundleStaticModules(root, staticModules(root, "js/start.js"))
  await import(pathToFileURL(path.join(root, "js/start.js")))
  assert.equal(globalThis.__onceBootstrapResult, 7)
  assert.equal(fs.readFileSync(path.join(root, "js/vapi-common.js"), "utf8"), "globalThis.__onceBootstrap = 1;")
})

