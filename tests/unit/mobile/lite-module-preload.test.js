const assert = require("node:assert/strict")
const fs = require("node:fs")
const os = require("node:os")
const path = require("node:path")
const test = require("node:test")
const { staticModules, prepare } = require("../../../scripts/prepare-lite-extension-modules")

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "once-module-preload-"))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.mkdirSync(path.join(root, "js"))
  const write = (file, source) => fs.writeFileSync(path.join(root, file), source)
  write("background.html", '<html><head></head><body><script src="classic.js"></script><script src="js/start.js" type="module"></script></body></html>')
  write("js/start.js", 'import "./shared.js"; export { value } from "./other.js"; import("./optional.js");')
  write("js/shared.js", 'import "./other.js"; export const value = 1;')
  write("js/other.js", 'export { value } from "./shared.js";')
  return { root, write }
}

test("static graph handles cycles and re-exports without preloading optional dynamic imports", t => {
  const { root } = fixture(t)
  assert.deepEqual(staticModules(root, "js/start.js"), ["js/start.js", "js/shared.js", "js/other.js"])
  const source = fs.readFileSync(path.join(root, "js/start.js"), "utf8")
  prepare(root)
  const html = fs.readFileSync(path.join(root, "background.html"), "utf8")
  assert.equal((html.match(/rel="modulepreload"/g) || []).length, 3)
  assert.ok(html.indexOf('src="classic.js"') < html.indexOf('src="js/start.js"'), "script evaluation order is unchanged")
  assert.equal(fs.readFileSync(path.join(root, "js/start.js"), "utf8"), source)
  prepare(root)
  assert.equal(fs.readFileSync(path.join(root, "background.html"), "utf8"), html, "repeated preparation is stable")
})

test("invalid dependencies fail the build instead of reading outside the extension", t => {
  const { root, write } = fixture(t)
  write("js/start.js", 'import "../../outside.js";')
  assert.throws(() => prepare(root), /leaves extension/)
  write("js/start.js", 'import "unresolved-package";')
  assert.throws(() => prepare(root), /Unsupported/)
  write("js/start.js", 'import "./missing.js";')
  assert.throws(() => prepare(root), /ENOENT/)
})

test("the current upstream background graph is complete and the vendor HTML stays untouched", () => {
  const root = path.resolve(__dirname, "../../../vendor/extensions/ublock-origin")
  const before = fs.readFileSync(path.join(root, "background.html"), "utf8")
  const graph = staticModules(root, "js/start.js")
  assert.ok(graph.includes("js/static-net-filtering.js"))
  assert.ok(graph.includes("lib/csstree/css-tree.js"))
  assert.ok(!graph.includes("js/benchmarks.js"))
  assert.equal(new Set(graph).size, graph.length)
  assert.equal(fs.readFileSync(path.join(root, "background.html"), "utf8"), before)
})

test("bundled entry facades preserve live shared state and leave dynamic code untouched", async t => {
  const { bundleStaticModules } = require("../../../scripts/bundle-lite-extension-modules")
  const { pathToFileURL } = require("node:url")
  const { root, write } = fixture(t)
  write("package.json", JSON.stringify({ type: "module" }))
  write("js/start.js", 'import { set } from "./shared.js"; set(9); export const optional = () => import("./optional.js");')
  write("js/shared.js", "globalThis.__onceModuleEvaluations = (globalThis.__onceModuleEvaluations || 0) + 1; export let value = 1; export const set = n => { value = n };")
  write("js/other.js", 'export { value, set } from "./shared.js";')
  const optional = 'export { value } from "./shared.js";'
  write("js/optional.js", optional)
  t.after(() => Reflect.deleteProperty(globalThis, "__onceModuleEvaluations"))
  const modules = staticModules(root, "js/start.js")
  const entries = await bundleStaticModules(root, modules)
  assert.ok(entries.includes("js/shared.js"), "outside imports retain their original entry URL")
  const start = await import(pathToFileURL(path.join(root, "js/start.js")))
  assert.equal(typeof start.optional, "function")
  const outside = await import(pathToFileURL(path.join(root, "js/other.js")))
  assert.equal(outside.value, 9)
  outside.set(23)
  const shared = await import(pathToFileURL(path.join(root, "js/shared.js")))
  assert.equal(shared.value, 23)
  assert.equal(globalThis.__onceModuleEvaluations, 1, "one module instance through bundled and original entry URLs")
  assert.equal(fs.readFileSync(path.join(root, "js/optional.js"), "utf8"), optional)
  assert.match(fs.readFileSync(path.join(root, "js/start.js"), "utf8"), /import\("\/js\/optional\.js"\)/)
  assert.ok(prepare(root).length < modules.length + entries.length)
})

