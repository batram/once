test("targeted writes are atomic, cross-window safe and delete credentials with their connection", async () => {
  const first = aiPlatform(), second = aiPlatform(first.shared, first.local)
  await Promise.all([
    editConnection(first.ai.store, { connection, token: "test-token", expected: null }),
    editConnection(second.ai.store, { connection: { ...connection, id: "other", name: "Other" }, expected: null })
  ])
  assert.equal((await first.ai.settings()).connections.length, 2)
  first.failWrites(true)
  await assert.rejects(editConnection(first.ai.store, { connection: { ...connection, name: "Changed" }, token: "new-token", expected: connection }), /disk full/)
  first.failWrites(false)
  assert.equal((await first.ai.settings()).connections[0].name, "Local")
  assert.match(JSON.parse(first.local.get("once:ai-local")).secrets["ai:local"], /test-token/)
  await editConnection(first.ai.store, { connection: { ...connection, name: "Changed" }, expected: connection })
  await assert.rejects(editConnection(second.ai.store, { connection, expected: connection }), /another window/)
  await removeConnection(first.ai.store, "local", { ...connection, name: "Changed" })
  assert.equal(JSON.parse(first.local.get("once:ai-local")).secrets["ai:local"], undefined)
})

test("one passphrase, recovery key and lock protect both datasets; switches are independent", async () => {
  const first = aiPlatform()
  await editConnection(first.ai.store, { connection, token: "secret-ai-token" })
  await selectModel(first.ai.store, null, { connection: connection.id, model: "fixture" })
  const created = await first.addons.create("shared correct horse battery", true, "Laptop")
  await first.ai.store.enable()
  assert.equal(first.shared.get("addon_vault")[0].value.version, 2)
  assert.equal(first.shared.has("ai_vault"), false)
  assert.equal(JSON.stringify([...first.shared.values()]).includes("secret-ai-token"), false)
  const second = aiPlatform(first.shared)
  await second.addons.vault.unlock("shared correct horse battery", false, true, "Phone")
  assert.equal(await second.ai.hasToken("local"), true)
  await second.addons.setEnabled(false)
  assert.equal(await second.addons.vault.participates("addons"), false)
  assert.equal(await second.addons.vault.participates("ai"), true)
  await second.ai.generate("reader.formatting", prompt)
  await second.ai.store.leave()
  assert.equal(await second.ai.hasToken("local"), true, "local copy survives leaving AI sync")
  await second.ai.store.enable()
  await second.addons.vault.lock()
  await assert.rejects(second.ai.settings(), /Unlock/)
  await second.addons.vault.unlock(created.recoveryKey, true, false, "Phone")
  assert.equal(await second.ai.hasToken("local"), true)
  assert.equal(await second.addons.vault.participates("addons"), false, "unlock does not re-enable an opted-out dataset")
  const restarted = aiPlatform(first.shared, first.local)
  assert.equal(await restarted.ai.hasToken("local"), true)
})

