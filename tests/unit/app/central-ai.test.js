test("truncated streams are rejected for every adapter and images use provider-specific blocks", () => {
  const event = value => `data: ${JSON.stringify(value)}\n\n`
  assert.throws(() => streamedResponse("compatible", event({ choices: [{ delta: { content: "partial" } }] })), /ended before/)
  assert.throws(() => streamedResponse("anthropic", event({ type: "content_block_start", index: 0, content_block: { type: "text", text: "partial" } })), /ended before/)
  assert.throws(() => streamedResponse("openai", event({ type: "response.output_text.delta", delta: "partial" })), /ended before/)
  const complete = streamedResponse("compatible", event({ choices: [{ delta: { content: "complete" }, finish_reason: "stop" }] }))
  assert.equal(providerResult("compatible", complete).text, "complete")
  for (const provider of ["openai", "anthropic", "compatible"]) {
    const payload = JSON.parse(providerRequest({ provider, model: "vision" }, "Read", "", [{ role: "user", content: [{ type: "image", mediaType: "image/png", base64: "aGVsbG8=" }] }], false).body)
    assert.match(JSON.stringify(payload), provider === "anthropic" ? /media_type/ : /image_url/)
    assert.doesNotMatch(JSON.stringify(payload), /"base64":/)
  }
})

test("shared request limits apply to built-in consumers and cancellation detaches native work", async () => {
  const runner = new AiRequestRunner(30)
  const never = () => new Promise(() => {})
  const signal = new AbortController()
  const pending = Array.from({ length: 3 }, () => runner.run("reader", signal.signal, never))
  signal.abort()
  await Promise.all(pending.map(request => assert.rejects(request, error => error.code === "cancelled")))
  await assert.rejects(runner.run("reader", undefined, never), error => error.code === "timeout")
  assert.equal(await runner.run("reader", undefined, async () => "next"), "next")
})

test("requests over the shared limits wait their turn instead of failing", async () => {
  const runner = new AiRequestRunner(1_000, 2, 3)
  const started = []
  const gates = []
  const held = name => runner.run(name, undefined, () => { started.push(name); return new Promise(resolve => gates.push(resolve)) })
  const settle = () => new Promise(resolve => setTimeout(resolve, 0))
  const first = [held("a"), held("a")]
  const third = held("a")
  // Consumer a is at its own bound; consumer b still gets the last overall slot.
  const other = held("b")
  await settle()
  assert.deepEqual(started, ["a", "a", "b"])
  // A waiter that is cancelled leaves the queue without ever starting.
  const leaving = new AbortController()
  const cancelled = runner.run("c", leaving.signal, async () => { started.push("c") })
  leaving.abort()
  await assert.rejects(cancelled, error => error.code === "cancelled")
  gates.shift()("done")
  assert.equal(await first[0], "done")
  await settle()
  assert.deepEqual(started, ["a", "a", "b", "a"])
  gates.forEach(resolve => resolve("done"))
  assert.deepEqual(await Promise.all([first[1], third, other]), ["done", "done", "done"])
})

test("migration fingerprints the source, preserves encryption and imports distinct conflicting configurations", async () => {
  const f = aiPlatform()
  const manifest = { protocol: 1, id: "what-wait-who-why", name: "What4", version: "1.6.4", contributions: [], connections: [{ id: "compatible", endpoint: "compatibleEndpoint", secret: "compatibleToken" }], settings: { type: "object", properties: {
    provider: { type: "string", default: "compatible" }, model: { type: "string", default: "old-model" }, compatibleEndpoint: { type: "string", format: "url", default: connection.endpoint }, compatibleToken: { type: "string", format: "secret" }
  } } }
  await f.settings.saveAddons(readAddonsDocument({ version: 1, addons: [{ manifest, enabled: true }] }))
  await f.addons.methods().saveAddonSecret(manifest.id, "compatibleToken", connection.endpoint, "old-token")
  await f.addons.create("shared correct horse battery", true, "Laptop")
  assert.equal(await migrateWhat4(f.ai, f.addons, f.platform), true)
  const settings = await f.ai.settings()
  assert.equal(settings.defaultModel.model, "old-model")
  assert.equal(await f.ai.hasToken(settings.defaultModel.connection), true)
  await migrateWhat4(f.ai, f.addons, f.platform)
  assert.equal((await f.ai.settings()).connections.length, 1)
  await f.addons.methods().saveAddonSecret(manifest.id, "compatibleToken", connection.endpoint, "replacement-token")
  await migrateWhat4(f.ai, f.addons, f.platform)
  assert.equal((await f.ai.settings()).connections.length, 2)
  assert.deepEqual((await f.ai.settings()).defaultModel, settings.defaultModel)
  assert.equal(f.shared.get("addon_vault")[0].value.version, 2)
})

test("a locked draft AI vault is retained, recovered once, and imported without replacing central defaults", async () => {
  const { SyncVault } = require("../../../packages/app/dist/SyncVault")
  const { LegacyAiImport } = require("../../../packages/app/dist/ai/LegacyAiImport")
  const f = aiPlatform()
  const port = { ...f.platform.listStore, readVault: () => f.platform.listStore.readVault("ai_vault"), writeVault: (value, parents) => f.platform.listStore.writeVault(value, parents, "ai_vault") }
  const legacy = new SyncVault(port, f.platform.secretStore, () => {}, "once:ai-vault")
  await legacy.create("old separate passphrase", true, "Old device", { document: { version: 1, addons: [] }, secrets: {}, scripts: {}, generation: 1, commit: "", author: "", updatedAt: new Date().toISOString() })
  await legacy.update(data => {
    data.ai = { version: 1, connections: [connection], searchConnections: [], defaultModel: { connection: "local", model: "old-model" }, overrides: {} }
    data.secrets["ai:local"] = JSON.stringify({ endpoint: connection.endpoint, value: "old-secret" })
  })
  await legacy.lock()
  await editConnection(f.ai.store, { connection, token: "central-secret" })
  await selectModel(f.ai.store, null, { connection: "local", model: "central-model" })
  await f.addons.create("one shared passphrase", true, "Current device")
  const importer = new LegacyAiImport(f.platform, f.ai.store)
  assert.equal(await importer.run(), false)
  assert.match(await importer.status(), /retained/)
  assert.equal(f.shared.has("ai_vault"), true)
  assert.equal(await importer.run("old separate passphrase"), true)
  assert.equal(await importer.status(), null)
  assert.equal((await f.ai.settings()).connections.length, 2)
  assert.equal((await f.ai.settings()).defaultModel.model, "central-model")
  assert.equal(await importer.run(), true)
  assert.equal((await f.ai.settings()).connections.length, 2)
})

test("removed consumer cleanup waits for shared unlock and retains linked consumers and connections", async () => {
  const { removedConsumers } = require("../../../packages/app/dist/ai/removedConsumers")
  const f = aiPlatform()
  await editConnection(f.ai.store, { connection, token: "saved-secret" })
  await selectModel(f.ai.store, "removed-addon", { connection: "local", model: "fixture" })
  await selectModel(f.ai.store, "linked-addon", { connection: "local", model: "fixture" })
  await f.addons.create("one shared passphrase", true, "Laptop")
  await f.ai.store.enable()
  const cleanup = removedConsumers(f.platform, f.ai.store, () => new Set(["linked-addon"]))
  await f.addons.vault.lock()
  await cleanup(["removed-addon", "linked-addon"])
  assert.ok(f.local.get("once:ai-removed-consumers"))
  await f.addons.vault.unlock("one shared passphrase", false, true, "Laptop")
  await cleanup()
  assert.equal((await f.ai.settings()).overrides["removed-addon"], undefined)
  assert.ok((await f.ai.settings()).overrides["linked-addon"])
  assert.equal(await f.ai.hasToken("local"), true)
})
